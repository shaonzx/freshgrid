// Downloads the photos listed in freshgrid-core/seed/data/images.json, resizes them to max 1200px WebP
// in seed/images/, draws branded placeholders for the rest, and writes seed/IMAGE_CREDITS.md.
// Usage: cd tools && npm install && node build-images.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const seed = join(here, '..', 'wp-content', 'plugins', 'freshgrid-core', 'seed');
const outDir = join(seed, 'images');
const manifest = JSON.parse(readFileSync(join(seed, 'data', 'images.json'), 'utf8'));
const UA = 'FreshGridSeed/1.0 (local store demo image import)';

mkdirSync(outDir, { recursive: true });

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// Prefer the standard 1280px thumbnail: lighter for Wikimedia and enough for a 1200px result.
function thumbUrl(url) {
	const match = url.match(/^(.*\/commons\/)(.\/..\/)([^/?]+)/);
	return match ? `${match[1]}thumb/${match[2]}${match[3]}/1280px-${match[3]}` : url;
}

async function fetchRetry(url) {
	for (let attempt = 0; attempt < 5; attempt++) {
		const res = await fetch(url, { headers: { 'User-Agent': UA } });
		if (res.status !== 429) {
			return res;
		}
		const wait = Math.max(Number(res.headers.get('retry-after')) || 0, 120);
		console.log(`rate limited, waiting ${wait}s`);
		await sleep(wait * 1000);
	}
	throw new Error('still rate limited');
}

async function download(url) {
	// A thumbnail wider than the original doesn't exist, so fall back to the original.
	let res = await fetchRetry(thumbUrl(url));
	if (!res.ok) {
		res = await fetchRetry(url);
	}
	if (!res.ok) {
		throw new Error(`HTTP ${res.status}`);
	}
	return Buffer.from(await res.arrayBuffer());
}

// Colors match the Global Styles palette at the time of writing.
function placeholder(label) {
	const leaf = 'M88 12C52 6 12 24 12 60c0 16 12 28 28 28C76 88 94 48 88 12Z';
	const lines = label.split(' & ');
	const text = lines
		.map((line, i) => `<text x="600" y="${800 + i * 76}" text-anchor="middle" font-family="Segoe UI, Arial, sans-serif" font-size="64" font-weight="600" fill="#1F2A25">${line}</text>`)
		.join('');
	return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="1200">
<rect width="1200" height="1200" fill="#F4F8F5"/>
<g transform="translate(420 260) scale(3.6)"><path d="${leaf}" fill="#177A52" opacity="0.18"/></g>
${text}
</svg>`);
}

const credits = [
	'# Image credits',
	'',
	'Every photo is CC0 or public domain according to the licence metadata on its Wikimedia Commons file page, so commercial use needs no attribution. Attribution below is a courtesy. Generated by `tools/build-images.mjs`.',
	'',
	'| Image | Source | Licence | Author |',
	'|---|---|---|---|',
];
const placeholders = [];
const failed = [];

for (const [key, item] of Object.entries(manifest)) {
	const file = join(outDir, `${key}.webp`);
	if (item.placeholder) {
		await sharp(placeholder(item.placeholder)).webp({ quality: 82 }).toFile(file);
		placeholders.push(`- \`${key}.webp\`: "${item.placeholder}"`);
		continue;
	}
	if (!existsSync(file)) {
		try {
			const source = await download(item.url);
			await sharp(source).rotate().resize({ width: 1200, height: 1200, fit: 'inside', withoutEnlargement: true }).webp({ quality: 78 }).toFile(file);
			console.log(key);
		} catch (error) {
			console.log(`FAILED ${key}: ${error.message}`);
			failed.push(key);
			continue;
		}
		await sleep(15000);
	}
	const author = (item.artist || 'Unknown').replace(/\|/g, '/').replace(/\s+/g, ' ');
	credits.push(`| \`${key}.webp\` | [${item.title.replace('File:', '').replace(/\|/g, '/')}](${item.page}) | ${item.license} | ${author} |`);
}

credits.push('', '## Branded placeholders', '', 'No suitable free photo was found for these, so they are generated in brand colors. Replace them with real product photos when available.', '', ...placeholders, '');
writeFileSync(join(seed, 'IMAGE_CREDITS.md'), credits.join('\n'));
console.log(`done: ${placeholders.length} placeholders, ${failed.length} failed`);
if (failed.length) {
	console.log(`Re-run to retry: ${failed.join(', ')}`);
	process.exit(1);
}
